"""Comprehensive decision-branch test suite for the Deterministic Risk Engine.

Targets 100% decision-branch coverage of all pre-trade safety controls:
- Global kill-switch (TRADING_ENABLED)
- Strict paper-mode enforcement
- Human-in-the-Loop consent validation
- Proposal existence, registration, and status
- Replay and duplicate-order prevention
- Proposal TTL expiration
- Quantity and order notional caps
- Position exposure caps (BUY)
- Inventory ownership and short-selling protection (SELL)
"""

from datetime import datetime, timedelta, timezone
import pytest

from app.core.config import Settings
from app.schemas.trading import (
    OrderApprovalRequest,
    OrderSide,
    OrderStatus,
    PortfolioPosition,
    PortfolioResponse,
    ProposedOrder,
)
from app.trading.risk import RiskEngine, proposal_registry


@pytest.fixture
def base_settings():
    return Settings(
        TRADING_MODE="paper",
        TRADING_ENABLED=True,
        ORDER_APPROVAL_REQUIRED=True,
        MAX_ORDER_NOTIONAL_USD=100.0,
        MAX_POSITION_NOTIONAL_USD=500.0,
    )


def test_risk_pass_valid_buy_proposal(base_settings):
    """A valid, unexpired BUY proposal under notional caps must pass all risk checks."""
    engine = RiskEngine(base_settings)
    now = datetime.now(timezone.utc)
    proposal = ProposedOrder(
        proposal_id="prop_valid_buy_1",
        symbol="AAPL",
        side=OrderSide.BUY,
        quantity=1,
        estimated_price=50.0,
        estimated_notional=50.0,
        status=OrderStatus.PROPOSED,
        created_at=now.isoformat(),
        expires_at=(now + timedelta(minutes=15)).isoformat(),
    )
    proposal_registry.register(proposal)

    req = OrderApprovalRequest(proposal_id=proposal.proposal_id, confirm=True)
    result, returned_prop = engine.evaluate_approval(req)

    assert result.passed is True
    assert returned_prop is not None
    assert returned_prop.proposal_id == proposal.proposal_id
    assert len(result.rejection_reasons) == 0


