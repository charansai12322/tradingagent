"""Comprehensive decision-branch test suite for the Deterministic Risk Engine.

Targets 100% decision-branch coverage of all pre-trade safety controls:
- Global kill-switch (TRADING_ENABLED)
- Strict paper-mode enforcement
- Human-in-the-Loop consent validation
- Proposal existence, registration, and status
- Replay and duplicate-order prevention
- Proposal TTL expiration
- Quantity and order notional caps
- Position exposure caps (BUY)
- Inventory ownership and short-selling protection (SELL)
"""

from datetime import datetime, timedelta, timezone
import pytest

